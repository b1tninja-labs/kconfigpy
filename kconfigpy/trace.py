"""From a hardware snapshot to a config fragment, keeping the reason for every option."""

from __future__ import annotations

import fnmatch
from dataclasses import dataclass, field
from pathlib import Path

from kconfigpy.kbuild import normalize
from kconfigpy.kconfig import KconfigDb
from kconfigpy.solve import Solution, Solver


@dataclass(frozen=True)
class Device:
    path: str
    modalias: str
    driver: str
    module: str


@dataclass
class Snapshot:
    devices: list[Device] = field(default_factory=list)
    loaded: list[str] = field(default_factory=list)


def read_snapshot(path: Path) -> Snapshot:
    """Read the tab-separated records written by ``kconfigpy snapshot``."""
    snapshot = Snapshot()
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split("\t")
        if fields[0] == "dev" and len(fields) >= 5:
            snapshot.devices.append(Device(fields[1], fields[2], fields[3], normalize(fields[4])))
        elif fields[0] == "mod" and len(fields) >= 2:
            snapshot.loaded.append(normalize(fields[1]))
    return snapshot


def read_excluded(path: Path) -> dict[str, str]:
    """Read an exclude list: one symbol per line, with or without ``CONFIG_``; ``#`` starts a comment."""
    excluded = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        name = line.split("#", 1)[0].strip().removeprefix("CONFIG_")
        if name:
            excluded[name] = f"listed in {path.name}"
    return excluded


def read_aliases(path: Path) -> list[tuple[str, str]]:
    """Read ``modules.alias`` as ``(pattern, module)`` pairs."""
    pairs = []
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[0] == "alias":
            pairs.append((parts[1], normalize(parts[2])))
    return pairs


def read_builtin_modinfo(path: Path) -> list[tuple[str, str]]:
    """Read ``(pattern, driver)`` pairs from ``modules.builtin.modinfo``, the ``name.alias=pattern`` records.

    A build with ``CONFIG_MODULES`` off never runs ``depmod``, so it has no ``modules.alias``; the aliases of
    what it built in are in this file, which the kernel build itself writes.
    """
    pairs = []
    for record in path.read_bytes().split(b"\0"):
        name, _, pattern = record.decode("utf-8", errors="replace").partition("=")
        driver, _, key = name.rpartition(".")
        if key == "alias" and driver and pattern:
            pairs.append((pattern, normalize(driver)))
    return pairs


def candidates(modalias: str, aliases: list[tuple[str, str]]) -> list[str]:
    """Modules whose alias patterns claim this device."""
    return sorted({module for pattern, module in aliases if fnmatch.fnmatchcase(modalias, pattern)})


@dataclass
class DeviceRow:
    device: Device
    status: str  # bound, available or unclaimed
    modules: list[str]
    symbols: list[str]


@dataclass
class Trace:
    rows: list[DeviceRow]
    solution: Solution
    loaded_only: dict[str, list[str]]
    unmapped: list[str]
    ambiguous: dict[str, list[str]] = field(default_factory=dict)
    builtin_statement: str | None = None


def trace(
    snapshot: Snapshot,
    db: KconfigDb,
    modules: dict[str, set[str]],
    aliases: list[tuple[str, str]],
    excluded: dict[str, str] | None = None,
) -> Trace:
    """Enable only what the bound devices need; list everything else for review.

    ``excluded`` maps a symbol to why the caller does not want it. It is never enabled, so nothing it
    depends on or selects is followed either.
    """
    solver = Solver(db)
    for name, why in (excluded or {}).items():
        solver.exclude(name, why)
    rows: list[DeviceRow] = []
    bound_modules: set[str] = set()
    unmapped: set[str] = set()
    for device in snapshot.devices:
        name = device.module or normalize(device.driver)
        if name:
            bound_modules.add(name)
            symbols = sorted(modules.get(name, set()))
            if not symbols:
                unmapped.add(name)
            for symbol in symbols:
                solver.want(symbol, f"device {device.modalias} uses driver {name}")
            rows.append(DeviceRow(device, "bound", [name], symbols))
            continue
        matches = candidates(device.modalias, aliases)
        symbols = sorted({s for m in matches for s in modules.get(m, set())})
        rows.append(DeviceRow(device, "available" if matches else "unclaimed", matches, symbols))
    loaded_only = {name: sorted(modules.get(name, set())) for name in sorted(set(snapshot.loaded) - bound_modules)}
    return Trace(rows, solver.solution, loaded_only, sorted(unmapped))


def fragment_text(result: Trace) -> str:
    lines = ["# Generated by kconfigpy. Each option is here for the reason given."]
    for symbol, why in sorted(result.solution.enabled.items()):
        lines.append(f"# {why}")
        lines.append(f"CONFIG_{symbol}=y")
    return "\n".join(lines) + "\n"


def _with_defaults(solution: Solution) -> dict[str, str]:
    """Each promptless symbol with who needs it, and what its defaults say where the request decides that."""
    out = {}
    for name, why in solution.assumed.items():
        if name in solution.default_on:
            why = f"{why}; predicted on: {solution.default_on[name]}"
        elif name in solution.default_off:
            why = f"{why}; predicted off: {solution.default_off[name]}"
        out[name] = why
    return out


def report_text(result: Trace) -> str:
    out = ["# Hardware trace", ""]
    if result.builtin_statement is not None:
        out += ["modules are off: drivers mapped to built-in symbols", "", result.builtin_statement, ""]
    for status in ("bound", "available", "unclaimed"):
        rows = [r for r in result.rows if r.status == status]
        out += [f"## {status.capitalize()} devices ({len(rows)})", ""]
        unique = {(r.device.modalias, tuple(r.modules), tuple(r.symbols)) for r in rows}
        out += [
            f"- `{a}`: {', '.join(m) or 'none'} -> {', '.join(s) or 'no option found'}" for a, m, s in sorted(unique)
        ]
        out.append("")
    solution = result.solution
    out += [f"## Options enabled ({len(solution.enabled)})", ""]
    out += [f"- `{s}`: {why}" for s, why in sorted(solution.enabled.items())]
    sections = [
        ("Forced by select, dependencies unmet", solution.forced),
        ("Excluded on request", solution.excluded),
        ("Conditional select not followed", solution.conditional),
        ("Must stay off", solution.forbidden),
        ("Left to the kernel (no prompt)", _with_defaults(solution)),
        ("Implied, likely on", solution.implied),
        ("Implied, not known to take effect", solution.implied_off),
        ("Not evaluated", solution.unknown),
        ("Undefined symbols", solution.undefined),
    ]
    for title, mapping in sections:
        out += ["", f"## {title} ({len(mapping)})", ""]
        out += [f"- `{k}`: {v}" for k, v in sorted(mapping.items())]
    out += ["", f"## Conflicts ({len(solution.conflicts)})", ""] + [f"- {c}" for c in solution.conflicts]
    out += ["", f"## Loaded but tied to no device ({len(result.loaded_only)})", ""]
    out += [f"- `{m}`: {', '.join(s) or 'no option found'}" for m, s in result.loaded_only.items()]
    out += ["", f"## Bound drivers with no Makefile match ({len(result.unmapped)})", ""]
    out += [
        f"- `{m}`: candidates {', '.join(result.ambiguous[m])}" if m in result.ambiguous else f"- `{m}`"
        for m in result.unmapped
    ]
    return "\n".join(out) + "\n"
