"""From a hardware snapshot to a config fragment, keeping the reason for every option."""

from __future__ import annotations

import fnmatch
from dataclasses import dataclass, field
from pathlib import Path

from kconfexplain.kbuild import normalize
from kconfexplain.kconfig import KconfigDb
from kconfexplain.solve import Solution, Solver


@dataclass(frozen=True)
class Device:
    path: str
    modalias: str
    driver: str
    module: str


@dataclass
class Snapshot:
    devices: list[Device] = field(default_factory=list)
    loaded: list[str] = field(default_factory=list)


def read_snapshot(path: Path) -> Snapshot:
    """Read the tab-separated output of ``tools/collect-snapshot.sh``."""
    snapshot = Snapshot()
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split("\t")
        if fields[0] == "dev" and len(fields) >= 5:
            snapshot.devices.append(Device(fields[1], fields[2], fields[3], normalize(fields[4])))
        elif fields[0] == "mod" and len(fields) >= 2:
            snapshot.loaded.append(normalize(fields[1]))
    return snapshot


def read_aliases(path: Path) -> list[tuple[str, str]]:
    """Read ``modules.alias`` as ``(pattern, module)`` pairs."""
    pairs = []
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[0] == "alias":
            pairs.append((parts[1], normalize(parts[2])))
    return pairs


def candidates(modalias: str, aliases: list[tuple[str, str]]) -> list[str]:
    """Modules whose alias patterns claim this device."""
    return sorted({module for pattern, module in aliases if fnmatch.fnmatchcase(modalias, pattern)})


@dataclass
class DeviceRow:
    device: Device
    status: str  # bound, available or unclaimed
    modules: list[str]
    symbols: list[str]


@dataclass
class Trace:
    rows: list[DeviceRow]
    solution: Solution
    loaded_only: dict[str, list[str]]
    unmapped: list[str]
    ambiguous: dict[str, list[str]] = field(default_factory=dict)


def trace(snapshot: Snapshot, db: KconfigDb, modules: dict[str, set[str]], aliases: list[tuple[str, str]]) -> Trace:
    """Enable only what the bound devices need; list everything else for review."""
    solver = Solver(db)
    rows: list[DeviceRow] = []
    bound_modules: set[str] = set()
    unmapped: set[str] = set()
    for device in snapshot.devices:
        name = device.module or normalize(device.driver)
        if name:
            bound_modules.add(name)
            symbols = sorted(modules.get(name, set()))
            if not symbols:
                unmapped.add(name)
            for symbol in symbols:
                solver.want(symbol, f"device {device.modalias} uses driver {name}")
            rows.append(DeviceRow(device, "bound", [name], symbols))
            continue
        matches = candidates(device.modalias, aliases)
        symbols = sorted({s for m in matches for s in modules.get(m, set())})
        rows.append(DeviceRow(device, "available" if matches else "unclaimed", matches, symbols))
    loaded_only = {name: sorted(modules.get(name, set())) for name in sorted(set(snapshot.loaded) - bound_modules)}
    return Trace(rows, solver.solution, loaded_only, sorted(unmapped))


def fragment_text(result: Trace) -> str:
    lines = ["# Generated by kconfexplain. Each option is here for the reason given."]
    for symbol, why in sorted(result.solution.enabled.items()):
        lines.append(f"# {why}")
        lines.append(f"CONFIG_{symbol}=y")
    return "\n".join(lines) + "\n"


def report_text(result: Trace) -> str:
    out = ["# Hardware trace", ""]
    for status in ("bound", "available", "unclaimed"):
        rows = [r for r in result.rows if r.status == status]
        out += [f"## {status.capitalize()} devices ({len(rows)})", ""]
        unique = {(r.device.modalias, tuple(r.modules), tuple(r.symbols)) for r in rows}
        out += [
            f"- `{a}`: {', '.join(m) or 'none'} -> {', '.join(s) or 'no option found'}" for a, m, s in sorted(unique)
        ]
        out.append("")
    solution = result.solution
    out += [f"## Options enabled ({len(solution.enabled)})", ""]
    out += [f"- `{s}`: {why}" for s, why in sorted(solution.enabled.items())]
    sections = [
        ("Must stay off", solution.forbidden),
        ("Left to the kernel (no prompt)", solution.assumed),
        ("Not evaluated", solution.unknown),
        ("Undefined symbols", solution.undefined),
    ]
    for title, mapping in sections:
        out += ["", f"## {title} ({len(mapping)})", ""]
        out += [f"- `{k}`: {v}" for k, v in sorted(mapping.items())]
    out += ["", f"## Conflicts ({len(solution.conflicts)})", ""] + [f"- {c}" for c in solution.conflicts]
    out += ["", f"## Loaded but tied to no device ({len(result.loaded_only)})", ""]
    out += [f"- `{m}`: {', '.join(s) or 'no option found'}" for m, s in result.loaded_only.items()]
    out += ["", f"## Bound drivers with no Makefile match ({len(result.unmapped)})", ""]
    out += [
        f"- `{m}`: candidates {', '.join(result.ambiguous[m])}" if m in result.ambiguous else f"- `{m}`"
        for m in result.unmapped
    ]
    return "\n".join(out) + "\n"
